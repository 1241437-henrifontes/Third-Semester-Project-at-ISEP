void board_draw_tracks(Track *tracks, int count) {
    printf("\n");
    printf("+--------+----------------+----------+\n");
    printf("| Track  |     State      | Train ID |\n");
    printf("+--------+----------------+----------+\n");

    for (int i = 0; i < count; i++) {
        printf("|  %2d    | %-14s |   %4d   |\n",
               tracks[i].id,
               tracks[i].state,
               tracks[i].trainId);
    }

    printf("+--------+----------------+----------+\n");
}

void board_draw_sensors(Config *config, Manager *m) {
    printf("\n");
    printf("+---------------------------------------+\n");
    printf("|           SENSOR INFORMATION           |\n");
    printf("+---------------------------------------+\n");

    outputSerial(config);

    manager_on_action(m, ACT_SENSOR_READ, 0, 0, NULL);

    printf("+---------------------------------------+\n");
}

